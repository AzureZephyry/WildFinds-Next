export function getMockFilterOptions(items: ItemCardViewModel[]) {
  const categories = Array.from(
    new Set(items.map((item) => item.category).filter((value): value is string => Boolean(value))),
  ).sort();
  const statuses = Array.from(
    new Set(items.map((item) => item.status).filter((value): value is string => Boolean(value))),
  ).sort();
  const buildings = Array.from(
    new Set(items.map((item) => item.building).filter((value): value is string => Boolean(value))),
  ).sort();

  return { categories, statuses, buildings };
}
